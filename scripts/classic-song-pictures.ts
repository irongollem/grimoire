// Writes src/classic/songPictures.generated.ts: the songs page's stand-in pictures (SONG_PICTURES in
// src/lib/icons.ts) as plain SVG markup, for the classic songs page (src/classic/), which runs without Vue on
// phones too old for the app. Rendered from the very components the app draws, so a song shows the same picture
// on both pages; songPictures.test.ts fails when the two drift.
//
//   npx tsx --tsconfig tsconfig.app.json scripts/classic-song-pictures.ts
import { writeFileSync } from "node:fs";
import { renderSongPictures } from "../src/classic/renderSongPictures";

const svgs = await renderSongPictures();
const body = `// Generated by scripts/classic-song-pictures.ts from SONG_PICTURES (src/lib/icons.ts). Do not edit.\n` +
  `export const SONG_PICTURE_SVGS: readonly string[] = ${JSON.stringify(svgs, null, 2)};\n`;
writeFileSync(new URL("../src/classic/songPictures.generated.ts", import.meta.url), body);
console.log(`classic song pictures: ${svgs.length} written`);
