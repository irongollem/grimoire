// Cartographer map data — see context/features/cartographer.md

import type { PackCategory, TileLight } from "@/cartographer/packSchema";

export type CellKey = `${number},${number}`;

export interface PackRef {
  pack_id: string;
  pack_version: number;
  variant: number;
  rotation?: number;
}

// `doorClosed` / `doorOpen` are the drawn state of a door edge and feed publish
// (`structure.ts DOOR_EDGE_KIND`); since schema 4 (#1065) they draw a doorway
// plus a leaf turned on its hinge. `grate` and `sluice` are wall-band fittings
// that cut the space flood fill like a wall and are never a way.
export type EdgeSegType = "wall" | "doorClosed" | "doorOpen" | "grate" | "sluice";

export interface EdgeSeg extends PackRef {
  type: EdgeSegType;
  /** A `wallDecal` variant set into this wall. Meaningful on `type: "wall"` only. */
  decal?: number;
}

export interface FloorCell {
  floor?: PackRef;
}

export type GroundWallMode = "none" | "visible" | "hidden";
export type BrushRegionMode = "new" | "extend";

/** Editable ground source. Floor/terrain cells are projections, never the material boundary itself. */
export interface GroundRegion {
  name: string;
  material: PackRef;
  category: "floor" | "terrainWater";
  z: number;
  /** Closed edge loops, including holes. This graph is never an occluder or a room divider. */
  boundary: Record<string, WallEdge>;
  /** Saved tile variation belongs to the source, so projecting a region preserves an existing map's art. */
  variants: Record<CellKey, number>;
  walls: {
    mode: GroundWallMode;
    material: PackRef;
    /** Only these physical segments belong to this shape. Unrelated walls are never regenerated. */
    ids: string[];
    /** Last emitted owned segments let a later boundary edit respect deletions made with the free wall tools. */
    segments: Record<string, WallEdge>;
    /** Shared/free perimeter stretches belong to somebody else and must never be regenerated by this shape. */
    excluded: WallEdge[];
  };
}

/**
 * One wall, door or fitting of the Drawing as a segment between two points in cell units (epic #1125 decision 5).
 * A wall on a grid line is keyed by its edge key (`latticeKey`: `"x,y:N"` is the top of cell (x,y), `"x,y:W"` its
 * left), an angled wall by a uuid. `a` and `b` are always stored so a reader never needs the key to know the line.
 */
export interface WallEdge extends EdgeSeg {
  a: [number, number];
  b: [number, number];
  /** `false` blocks sight and light but is not drawn (an imported wall over a picture that already shows it). */
  visible?: boolean;
  /**
   * The wall asks to curve through its end at `a` (`smoothA`) or `b` (`smoothB`). A node is smooth only where exactly
   * two angled walls meet and both ask for it there; a junction of three, a door end and a lattice wall end are
   * corners whatever the flags say. A lattice wall never carries them. Kept on the walls so they travel through every
   * edit without a record of their own (#1125, wall curves).
   */
  smoothA?: true;
  smoothB?: true;
}

/** A light the DM placed (epic #1125 story 5), at a point in cell units. */
export interface PlacedLight {
  x: number;
  y: number;
  light: TileLight;
}

export type SolidCell = PackRef;

/** A per-cell ground material (the pack's `terrainWater`), drawn instead of the floor in its cell. */
export type TerrainCell = PackRef;

export interface ObjectCell extends PackRef {
  category: PackCategory;
  side?: string;
}

export interface AnnotationCell {
  text?: string;
  icon?: string;
  color?: string;
}

export interface CellMetadata {
  trap_id?: string;
  feature_id?: string;
  encounter_id?: string;
  note_id?: string;
  npc_spawn_ids?: string[];
  monster_spawn_ids?: string[];
}

/**
 * One prop from the Dressing library placed on a map (epic #1062). Props sit
 * on their own layer, not in the cell grids: they cover several cells, turn
 * to any angle, and overlap each other.
 */
export interface DressingPlacement {
  prop_id: string;
  /** Anchor cell: the top-left of the footprint as turned to the nearest
   *  quarter, so a quarter-turned 2x1 table stands 1x2 from here on whole cells. */
  x: number;
  y: number;
  /** Degrees 0-359, clockwise, about that footprint's centre (dressingCentre). */
  rotation: number;
  /** Stacking order, higher draws on top. Stored because jsonb does not
   *  preserve object key order, so insertion order could not say which prop
   *  is on top after a reload. */
  z: number;
}

export interface DungeonMapLayers {
  ground: Record<string, GroundRegion>;
  floor: Record<CellKey, FloorCell>;
  solidBlock: Record<CellKey, SolidCell>;
  /** A per-cell ground material, drawn instead of the floor in its cell. */
  terrain: Record<CellKey, TerrainCell>;
  object: Record<CellKey, ObjectCell>;
  annotation: Record<CellKey, AnnotationCell>;
  /** Keyed by a placement uuid. */
  dressing: Record<string, DressingPlacement>;
  /** Walls, doors and fittings as segments: lattice edges by edge key, angled walls by uuid (see `WallEdge`). */
  walls: Record<string, WallEdge>;
  /** Lights placed by hand, keyed by a uuid. */
  lights: Record<string, PlacedLight>;
}

/**
 * How lit the whole map is (epic #1073), the rules' three: daylight is bright light everywhere, dim is dim light
 * everywhere (twilight), dark is darkness wherever no light reaches. One level per map.
 */
export type DarknessLevel = "daylight" | "dim" | "dark";

export interface DungeonMap {
  id: string;
  user_id: string;
  /** NULL = available in every campaign; set = only visible when that campaign
   *  is active. The DM picks, per map (#789) — existing rows stay null. */
  campaign_id: string | null;
  name: string;
  description: string | null;
  layers: DungeonMapLayers;
  metadata: Record<CellKey, CellMetadata>;
  default_pack_id: string | null;
  /** The map's ambient light. Counts toward `rev`, so changing it makes a published site stale. */
  darkness: DarknessLevel;
  tags: string[];
  notes: unknown; // Tiptap JSON
  /** Bumped by a DB trigger whenever `layers` or `metadata` change (#868).
   *  `locations.map_published_rev` records which rev a site last received. */
  rev: number;
  created_at: string;
  updated_at: string;
}

export type DungeonMapInsert = Omit<DungeonMap, "id" | "user_id" | "created_at" | "updated_at" | "rev">;
export type DungeonMapUpdate = Partial<DungeonMapInsert>;

export function emptyLayers(): DungeonMapLayers {
  return { ground: {}, floor: {}, solidBlock: {}, terrain: {}, object: {}, annotation: {}, dressing: {}, walls: {}, lights: {} };
}

/**
 * A map saved before a layer existed reads that layer as empty; the DB
 * default carries every key for new rows, but older rows lack the newer ones.
 * A layer that is present but not an object (jsonb `null`) reads as empty too:
 * a spread would keep the `null`, and every reader calls `Object.keys` on it.
 */
export function withLayerDefaults(raw: Partial<DungeonMapLayers> | null | undefined): DungeonMapLayers {
  // `area` is the retired brush coverage; `convertAreaLayer` has already made walls of it before a map gets here.
  const present = Object.fromEntries(
    Object.entries(raw ?? {}).filter(([name, layer]) => name !== "area" && typeof layer === "object" && layer !== null),
  );
  return { ...emptyLayers(), ...present };
}

/**
 * How many cells of a map have anything painted on them: floor, water, rock or an object. Each cell
 * counts once, however many layers it has (a floor cell with a barrel on it is one painted cell).
 */
export function paintedCellCount(layers: DungeonMapLayers): number {
  const cells = new Set<string>();
  for (const layer of [layers.floor, layers.terrain, layers.solidBlock, layers.object]) {
    for (const key of Object.keys(layer)) cells.add(key);
  }
  return cells.size;
}

export function cellKey(x: number, y: number): CellKey {
  return `${x},${y}`;
}

export function parseCellKey(key: CellKey): [number, number] {
  const [x, y] = key.split(",");
  return [Number(x), Number(y)];
}
