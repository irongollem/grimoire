-- #1124: move seven library books from Open5e v1 keys to the v2 document keys.
--
-- Until now these books kept their v1 keys and the importers translated Open5e v2
-- back to them (LEGACY_DOCUMENT_KEY_ALIASES). That alias layer is gone: a book's key
-- is its Open5e v2 document key, as it already was for the SRD, so the normal seeds
-- maintain these books like any other.
--
--   cc -> ccdx, blackflag -> bfrd, dmag -> deepm, dmag-e -> deepmx,
--   warlock -> wz, o5e -> open5e, taldorei -> tdcs
--
-- Row ids never change, so nothing that points at a row (characters, encounters,
-- inventories, curatedSpellMechanics.json) needs touching. Library rows also move
-- their source_record_key to the v2 record key, from a name match against Open5e
-- v2 done on 1 Nov 2026 (1,646 of 1,647 production rows; spells from their
-- provenance.mechanics_enriched_from.record). The one row Open5e v2 does not hold,
-- the Skysail item promoted from a vault (#995), keeps its own record key under tdcs.
--
-- A5E (a5e, menagerie) is deliberately left on its old keys: frozen, owned by #934.
--
-- Tome of Heroes (toh) and Kobold Press (kp) keep their book keys, which already match,
-- but their spells move to v2 record keys too, for the same reason.
--
-- Every statement is a no-op on a database without these books.

-- 1. The book registry. No row in the tables that reference content_sources(key)
--    uses these keys, so the key can change in place.
update public.content_sources c
set key = v.new_key, open5e_key = v.new_key
from (values
  ('cc', 'ccdx'),
  ('blackflag', 'bfrd'),
  ('dmag', 'deepm'),
  ('dmag-e', 'deepmx'),
  ('warlock', 'wz'),
  ('o5e', 'open5e'),
  ('taldorei', 'tdcs')
) as v(old_key, new_key)
where c.key = v.old_key;

