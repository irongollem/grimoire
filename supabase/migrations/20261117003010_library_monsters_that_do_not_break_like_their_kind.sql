-- Library monsters that do not break like their kind (#1203).
--
-- A monster's morale (when it breaks, and whether it then flees, surrenders or fights on) is derived from its stat
-- block when `stat_block.tactics.morale` is absent: undead, constructs, oozes, plants and mindless things never break,
-- everyone else breaks at a quarter of its hit points and flees. That is right for what is typical and wrong for the
-- kinds whose nature matters more than their Intelligence: a fire elemental or a bound devil does not run, a hag or a
-- rakshasa bargains, a mephit or an imp bolts early.
--
-- So the 806 fiends, celestials, elementals and fey in the library were reviewed one by one against their derived
-- value (16 Nov 2026, by model, in batches, from published lore where it exists and the creature's own page where it
-- does not), and the 279 below get a stored value. The maintainer approved the whole list, the arguable ones
-- included ("most of those arguable ones are probably more likely true than false"). Who a creature goes for was
-- reviewed in the same pass and nothing was changed. The principle: rules where logical, a stored value where a
-- creature is not typical of its kind.
--
-- Only `morale` is written, merged into whatever `tactics` a row already has. A row that already carries a morale is
-- left alone (nobody has set one yet, so this only matters if the migration is replayed over later edits). An id the
-- library does not have is skipped. The stat-block write guard passes `tactics` through.
--
-- A re-import of a monster from Open5e rebuilds its stat block from the source fields, which have no tactics, and
-- would silently drop this key. So the table keeps it: an update whose new stat block has no `tactics` carries the
-- old one over (`private.keep_library_monster_tactics`). Library rows are read-only in the app, so nothing there
-- clears tactics by leaving them out; to remove them on purpose, write `"tactics": {}`.

create or replace function private.keep_library_monster_tactics()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.stat_block is not null
     and old.stat_block ? 'tactics'
     and not (new.stat_block ? 'tactics') then
    new.stat_block := new.stat_block || jsonb_build_object('tactics', old.stat_block -> 'tactics');
  end if;
  return new;
end;
$$;

revoke execute on function private.keep_library_monster_tactics() from public, anon, authenticated;

